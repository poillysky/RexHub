"""115 文件名规则：压缩包后缀与密码标记（转存 / 解压 / 改名共用一份）。"""

import re

# 转存改名、云解压、本地解压都按这个后缀判断压缩包
ARCHIVE_RE = re.compile(r"\.(zip|rar|7z)$", re.I)

# 文件名里的密码标记：xxx [密码 abc] / xxx【密码:abc】（兼容旧标记）
PASSWORD_TAG_RE = re.compile(
    r"(?:【\s*(?:解压)?密码\s*[:：]\s*[^】]*】|\[\s*密码\s*[:：]?\s*[^\]]*\])"
)

# 同一标记但要取出密码本身：本地兜底解压先试名称里写的密码
PASSWORD_CAPTURE_RE = re.compile(
    r"(?:【\s*(?:解压)?密码\s*[:：]\s*([^】]*?)\s*】|\[\s*密码\s*[:：]?\s*([^\]]*?)\s*\])"
)
